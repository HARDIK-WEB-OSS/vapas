import argparse
import sys
from collections import Counter
from pathlib import Path

from vapas.classify.channel_rules import CLASSIFIER_VERSION, Channel, classify
from vapas.synthetic.narrations import corpus

REPORT = Path(__file__).resolve().parents[2] / "docs" / "channel_eval.md"


def percent(part: int, whole: int) -> str:
    return f"{100 * part / whole:.1f}%" if whole else "n/a"


def evaluate(seed: int, per_template: int) -> str:
    items = corpus(seed, per_template)
    predicted: Counter[Channel] = Counter()
    actual: Counter[Channel] = Counter()
    correct: Counter[Channel] = Counter()
    confusion: Counter[tuple[Channel, Channel]] = Counter()
    kinds_right = refs_right = covered = 0
    for item in items:
        result = classify(item.narration, item.direction)
        predicted[result.channel] += 1
        actual[item.channel] += 1
        covered += result.channel is not Channel.UNCLASSIFIED
        kinds_right += result.kind is item.kind
        refs_right += result.reference == item.reference
        if result.channel is item.channel:
            correct[item.channel] += 1
        else:
            confusion[(item.channel, result.channel)] += 1
    lines = [
        "# Channel rules on synthetic narrations",
        "",
        f"Generated by `backend/scripts/eval_channels.py --seed {seed} --per-template {per_template}`, "
        f"classifier version {CLASSIFIER_VERSION}.",
        "",
        "Warning: the rules and the synthetic templates were written by the same person, so these numbers only show",
        "the two are consistent. Real coverage and precision come from `backend/scripts/measure_rule_coverage.py` on",
        "labelled private statements (PENDING REAL DATA). The LightGBM fallback is built only if real coverage is",
        "below about 95%.",
        "",
        f"- Narrations: {len(items)}",
        f"- Coverage (any channel assigned): {percent(covered, len(items))}",
        f"- Kind correct: {percent(kinds_right, len(items))}",
        f"- Reference correct: {percent(refs_right, len(items))}",
        "",
        "| Channel | Actual | Predicted | Precision | Recall |",
        "|---|---|---|---|---|",
    ]
    for channel in Channel:
        lines.append(
            f"| {channel.value} | {actual[channel]} | {predicted[channel]} | "
            f"{percent(correct[channel], predicted[channel])} | {percent(correct[channel], actual[channel])} |"
        )
    lines += [
        "",
        "Confusions (actual -> predicted): "
        + (", ".join(f"{a.value} -> {p.value}: {n}" for (a, p), n in confusion.most_common()) or "none"),
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Measure channel rules on the synthetic narration corpus.")
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--per-template", type=int, default=50)
    parser.add_argument("--write", action="store_true", help=f"write the report to {REPORT}")
    args = parser.parse_args()
    text = evaluate(args.seed, args.per_template)
    print(text)
    if args.write:
        REPORT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
