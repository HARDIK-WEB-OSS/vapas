import argparse
import asyncio
import io
import sys
from pathlib import Path
from typing import Any

import yaml
from sqlalchemy.ext.asyncio import create_async_engine

from vapas.config import get_settings
from vapas.knowledge.search import ClauseHit, search

QUESTIONS = Path(__file__).resolve().parents[1] / "src" / "vapas" / "knowledge" / "eval_questions.yaml"
REPORT = Path(__file__).resolve().parents[2] / "docs" / "knowledge_eval.md"
TARGET = 0.9


def load_questions() -> list[dict[str, Any]]:
    data: list[dict[str, Any]] = yaml.safe_load(QUESTIONS.read_text(encoding="utf-8"))["questions"]
    return data


async def run(questions: list[dict[str, Any]]) -> list[list[ClauseHit]]:
    engine = create_async_engine(get_settings().database_url.get_secret_value())
    try:
        async with engine.connect() as conn:
            return [await search(conn, q["question"]) for q in questions]
    finally:
        await engine.dispose()


def rank_of(hits: list[ClauseHit], expected: list[str]) -> int | None:
    return next((i + 1 for i, h in enumerate(hits) if [h.instrument_id, h.clause] == expected), None)


def main() -> int:
    parser = argparse.ArgumentParser(description="Recall of clause search on the 30 evaluation questions.")
    parser.add_argument("--write", action="store_true", help=f"write the report to {REPORT}")
    args = parser.parse_args()
    questions = load_questions()
    results = asyncio.run(run(questions))
    ranks = [rank_of(hits, q["expected"]) for q, hits in zip(questions, results, strict=True)]
    at1 = sum(r == 1 for r in ranks) / len(ranks)
    at5 = sum(r is not None for r in ranks) / len(ranks)
    misses = [
        f'- "{q["question"]}" expected {q["expected"][1]} ({q["expected"][0]}); got '
        + (", ".join(h.clause for h in hits) or "not found")
        for q, hits, r in zip(questions, results, ranks, strict=True)
        if r is None
    ]
    lines = [
        "# Knowledge base search evaluation",
        "",
        f"Generated by `backend/scripts/eval_knowledge.py` on {len(questions)} questions "
        "(`backend/src/vapas/knowledge/eval_questions.yaml`).",
        "",
        "Search: Postgres full-text search over clause rows with a small domain thesaurus for everyday words.",
        "The questions and the thesaurus were written by the same person, so these numbers are optimistic;",
        "real user questions will be measured in the pilot.",
        "",
        f"- recall@1: {at1:.3f}",
        f"- recall@5: {at5:.3f} (target {TARGET}; pgvector hybrid search only if below)",
        "",
        "Misses:" + ("" if misses else " none"),
        *misses,
    ]
    text = "\n".join(lines) + "\n"
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    print(text)
    if args.write:
        REPORT.write_text(text, encoding="utf-8")
    return 0 if at5 >= TARGET else 1


if __name__ == "__main__":
    sys.exit(main())
