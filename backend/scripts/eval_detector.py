import argparse
import io
import sys
from collections import Counter
from datetime import date
from pathlib import Path

from vapas.detect.engine import detect
from vapas.detect.model import Detector, Level
from vapas.rules.loader import load_rulebook
from vapas.synthetic.scenarios import build

REPORT = Path(__file__).resolve().parents[2] / "docs" / "detector_eval.md"
AS_OF = date(2026, 11, 20)
PRECISION_TARGET = 0.95


def main() -> int:
    parser = argparse.ArgumentParser(description="Detector precision on synthetic histories with injected cases.")
    parser.add_argument("--users", type=int, default=200)
    parser.add_argument("--write", action="store_true", help=f"write the report to {REPORT}")
    args = parser.parse_args()
    rulebook = load_rulebook()
    true_positive = false_positive = false_negative = wrong_amount = 0
    labels: Counter[str] = Counter()
    levels: Counter[str] = Counter()
    false_positives: list[str] = []
    for seed in range(1, args.users + 1):
        scenario = build(seed)
        labels.update(scenario.labels)
        findings = detect(scenario.transactions, scenario.answers, rulebook, AS_OF, 12, lambda n: n)
        levels.update(f"{f.detector.value}:{f.level.value}" for f in findings)
        claims = {f.debit: f for f in findings if f.level is Level.CLAIM and f.detector is Detector.LATE_REVERSAL}
        for key, finding in claims.items():
            expected = scenario.expected_claims.get(key) if key else None
            if expected is None:
                false_positive += 1
                false_positives.append(f"user {seed}: {finding.why}")
            elif expected != finding.amount_owed_paise:
                wrong_amount += 1
                false_positives.append(f"user {seed}: wrong amount {finding.amount_owed_paise} vs {expected}")
            else:
                true_positive += 1
        false_negative += sum(1 for key in scenario.expected_claims if key not in claims)
    predicted = true_positive + false_positive + wrong_amount
    precision = true_positive / predicted if predicted else 1.0
    recall = true_positive / (true_positive + false_negative) if true_positive + false_negative else 1.0
    lines = [
        "# Detector evaluation on synthetic histories",
        "",
        f"Generated by `backend/scripts/eval_detector.py --users {args.users}` (as of {AS_OF}).",
        "",
        "Each synthetic user has about 260 noise transactions plus injected cases with known answers. This checks",
        "the detection logic only; real precision comes from manual review of real statements (PENDING REAL DATA).",
        "",
        f"- Claims predicted: {predicted}",
        f"- Correct claims (right transaction and exact amount): {true_positive}",
        f"- False positives: {false_positive}; wrong amounts: {wrong_amount}",
        f"- Missed claims: {false_negative}",
        f"- Claim precision: {precision:.3f} (target {PRECISION_TARGET})",
        f"- Claim recall: {recall:.3f}",
        "",
        "Injected cases: " + ", ".join(f"{k} {v}" for k, v in sorted(labels.items())),
        "",
        "Findings by detector and level: " + ", ".join(f"{k} {v}" for k, v in sorted(levels.items())),
        "",
        "False positives:" + ("" if false_positives else " none"),
        *[f"- {line}" for line in false_positives],
    ]
    text = "\n".join(lines) + "\n"
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    print(text)
    if args.write:
        REPORT.write_text(text, encoding="utf-8")
    return 0 if precision >= PRECISION_TARGET else 1


if __name__ == "__main__":
    sys.exit(main())
