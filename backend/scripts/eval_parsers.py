import argparse
import sys
import time
from collections import defaultdict
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from vapas.ingest.model import FileKind, ParseError
from vapas.ingest.parse import parse_document
from vapas.ingest.reconcile import reconcile
from vapas.synthetic.generator import (
    STYLES,
    SyntheticStatement,
    expected_rows,
    generate,
    render_csv,
    render_pdf,
    render_xls,
    render_xlsx,
)

REPORT = Path(__file__).resolve().parents[2] / "docs" / "parser_eval.md"
RENDERERS: dict[FileKind, Callable[[SyntheticStatement], bytes]] = {
    FileKind.PDF: render_pdf,
    FileKind.CSV: render_csv,
    FileKind.XLSX: render_xlsx,
    FileKind.XLS: render_xls,
}


@dataclass
class Tally:
    statements: int = 0
    reconciled: int = 0
    rows_expected: int = 0
    rows_exact: int = 0
    errors: int = 0
    seconds: float = 0.0
    pages: int = 0
    failures: list[str] = field(default_factory=list)


def evaluate(count: int, rows: int) -> dict[tuple[str, FileKind], Tally]:
    tallies: dict[tuple[str, FileKind], Tally] = defaultdict(Tally)
    for bank in STYLES:
        for seed in range(count):
            synthetic = generate(bank, 1000 + seed, rows)
            truth = expected_rows(synthetic)
            for kind, render in RENDERERS.items():
                tally = tallies[(bank, kind)]
                tally.statements += 1
                tally.rows_expected += len(truth)
                data = render(synthetic)
                started = time.perf_counter()
                try:
                    parsed = parse_document(data, kind)
                except ParseError as error:
                    tally.errors += 1
                    tally.failures.append(f"seed {seed}: {error.code}")
                    continue
                tally.seconds += time.perf_counter() - started
                tally.pages += parsed.pages
                tally.rows_exact += sum(a == b for a, b in zip(parsed.rows, truth, strict=False))
                tally.reconciled += reconcile(parsed.rows, parsed.opening_balance_paise).reconciled
    return tallies


def percent(part: int, whole: int) -> str:
    return f"{100 * part / whole:.1f}%" if whole else "n/a"


def report(tallies: dict[tuple[str, FileKind], Tally], count: int, rows: int) -> str:
    lines = [
        "# Parser evaluation on synthetic statements",
        "",
        f"Generated by `backend/scripts/eval_parsers.py --count {count} --rows {rows}`.",
        "",
        "These numbers prove the parser matches the synthetic generator, which follows layouts assumed from general",
        "knowledge of each bank. They say nothing about real bank statements; see `docs/pending_real_data.md`.",
        "",
        "| Bank | Format | Statements | Rows parsed exactly | Statements reconciled | Errors | Seconds per page |",
        "|---|---|---|---|---|---|---|",
    ]
    for (bank, kind), t in sorted(tallies.items()):
        per_page = f"{t.seconds / t.pages:.3f}" if t.pages else "n/a"
        lines.append(
            f"| {bank} | {kind.value} | {t.statements} | {percent(t.rows_exact, t.rows_expected)} | "
            f"{percent(t.reconciled, t.statements)} | {t.errors} | {per_page} |"
        )
    pdf = [t for (_, kind), t in tallies.items() if kind is FileKind.PDF]
    pages = sum(t.pages for t in pdf)
    if pages:
        lines += ["", f"PDF parsing time on this machine: {sum(t.seconds for t in pdf) / pages:.3f} s per page."]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Measure parser accuracy on synthetic statements.")
    parser.add_argument("--count", type=int, default=10)
    parser.add_argument("--rows", type=int, default=120)
    parser.add_argument("--write", action="store_true", help=f"write the report to {REPORT}")
    args = parser.parse_args()
    tallies = evaluate(args.count, args.rows)
    text = report(tallies, args.count, args.rows)
    print(text)
    if args.write:
        REPORT.write_text(text, encoding="utf-8")
    perfect = all(t.rows_exact == t.rows_expected and t.reconciled == t.statements for t in tallies.values())
    return 0 if perfect else 1


if __name__ == "__main__":
    sys.exit(main())
